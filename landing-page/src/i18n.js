export function applyLanguage(lang) {
  contentMap.forEach(item => {
    const els = document.querySelectorAll(item.q);
    const elementsToUpdate = item.i !== undefined ? [els[item.i]] : Array.from(els);
    
    elementsToUpdate.forEach(el => {
      if (el) {
        if (item.attr) {
          el.setAttribute(item.attr, item[lang]);
        } else if (item.isHtml) {
          el.innerHTML = item[lang];
        } else {
          el.textContent = item[lang];
        }
      }
    });
  });
  
  // Update flag buttons UI
  document.querySelectorAll('.lang-btn, .lang-btn-mobile').forEach(btn => {
    if (btn.dataset.lang === lang) {
      btn.classList.remove('opacity-50', 'grayscale', 'text-on-surface-variant');
      btn.classList.add('active', 'text-primary');
      if (btn.classList.contains('lang-btn-mobile')) {
         btn.classList.add('bg-primary/10');
      }
    } else {
      btn.classList.add('opacity-50', 'grayscale', 'text-on-surface-variant');
      btn.classList.remove('active', 'text-primary');
      if (btn.classList.contains('lang-btn-mobile')) {
         btn.classList.remove('bg-primary/10');
      }
    }
  });
  
  // Update HTML lang attribute
  document.documentElement.lang = lang;
}
